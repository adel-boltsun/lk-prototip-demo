/* Экран 5 «Бонусы».
   Половина смысла кабинета: сколько врачу начислено, сколько уже выплачено
   и сколько ждёт выплаты, а под итогом — история операций, где видно, за
   какого пациента и какую услугу пришло начисление.

   🔴 Композиция собрана приёмами общего слоя, а не заново. Экран собирали
   из компонентов, и владелец забраковал сборку: дизайн-система давала
   детали, а композицию — нет. Что переезд поменял против прежней сборки:

   1. Три числа стоят крупными якорями в карточке на зонах (приёмы 3 и 4) —
      той же, что несёт «ждёт ответа» на модерации и блок денег в карточке
      партнёра. Прежние ячейки итогов приехали из сметы пациента: там
      четвёртая ячейка это срок оплаты, и колонки приходилось переобъявлять
      экрану под три числа.
   2. Правило начисления — полоса-пояснение (приём 2), а не своя строка со
      значком: ровно ту же полосу под своей таблицей рисуют «Мои направления»
      и табло клиники. Двух почти одинаковых строк под числами больше нет —
      слова шва про ставку стоят один раз и в одном месте.
   3. История переехала с пациентской таблицы на таблицу на зонах (приём 6).
      Зоны те же, что в «Моих направлениях», включая объединённую зону
      «сумма и начисление»: на узком окне зоны встают столбиком сами, и
      голое число не остаётся без подписи, когда шапка таблицы спрячется.
   4. Пустое состояние — общий блок со значком в круге ({round}), как на
      утверждённых рисунках кабинета.

   🔴 Ставку начисления назначил владелец на время показа, своего правила
   клиника не давала. Поэтому из шва приходит не только число, но и СЛОВА
   о нём: правило — полосой под тремя числами, подпись к колонке — сноской
   от Render.referralBonusColumn, которая выдаёт короткую форму числа и её
   сноску одним вызовом. Экран ставку не называет и процента не печатает:
   сочинённая здесь вторая ставка стала бы выдуманным фактом о клинике, и
   показ не отличил бы её от решения владельца.

   Состояния — по таблице спецификации, экран 5: есть начисления и пусто.
   Данные только через DATA, повторяющиеся блоки — через Render.
   Утверждения по таблице состояний — tools/test-vrach-bonusy.html. */
(function (w) {
  'use strict';

  var fmt = w.Render.fmt;
  var section = w.Render.section;

  function esc(v) { return w.Render.esc(v); }
  function ic(n, c) { return w.icon ? w.icon(n, c) : ''; }

  /* --- деньги: три числа, а не одно --------------------------------------
     Начислено, выплачено и ждёт выплаты стоят рядом и врозь: одно число
     «начислено» на этом экране отвечает на вопрос «сколько заработал», но
     не на вопрос «сколько уже пришло», а спрашивают именно второй.

     Подписи к нулям другие: «клиника перевела» под нулём утверждает перевод,
     которого не было. */
  function anchor(label, value, note) {
    return { body: w.Render.anchor({ label: label, value: value, note: note }) };
  }

  function moneyCard(b) {
    var empty = !b.items.length;
    return w.Render.zoneCard({ cls: 'bn-money', zones: [
      anchor('Начислено всего', fmt.money(b.accrued),
             empty ? 'Начислений пока нет' : 'нарастающим итогом'),
      anchor('Выплачено', fmt.money(b.paid),
             empty ? 'Переводов пока не было' : 'клиника перевела'),
      anchor('Ждёт выплаты', fmt.money(b.pending),
             empty ? 'Ждать пока нечего' : 'начислено, ещё не переведено'),
      /* Правило стоит зоной во всю ширину под всеми тремя числами — так его
         ставит рисунок карточки партнёра, и так оно попадает внутрь той же
         коробки, что и числа. Порознь у каждого числа оно читалось бы как три
         разных правила, а вынесенное под карточку — как хвост, к числам уже
         не относящийся.
         🔴 Фразу целиком отдаёт шов. Экран не выкраивает из неё половину и не
         пересказывает своими словами: пересказ ставки — это и есть та вторая
         ставка, которой на экране быть не должно. */
      { cls: 'bn-money__rule',
        body: w.Render.hintBar({ icon: 'warn', cls: 'bn-rule', text: b.rule }) }
    ] });
  }

  /* --- история операций ---------------------------------------------------
     Строка на операцию. За что начислено, видно в самой строке: пациент,
     услуга и её цена стоят рядом с суммой начисления — по историям 15 и 16
     врач должен понимать, за что пришли деньги, не открывая направление. */

  function patient(it) {
    /* Номер направления под именем: по нему строку находят в «Моих
       направлениях», и без него «за что начислено» упирается в одноимённых
       пациентов. Начисление без своего направления невозможно, но проверка
       стоит: строку рисуем и тогда, когда шов его не отдал. */
    var ref = w.DATA.referral(it.id);
    return '<span class="bn-name">' + esc(it.patientName) + '</span>' +
      (ref && ref.number
        ? '<span class="bn-sub"><span class="bn-nw">' + esc(ref.number) + '</span></span>'
        : '');
  }

  function service(it) {
    return '<span class="bn-svc">' + esc(it.serviceTitle) + '</span>' +
      '<span class="bn-sub">начислено ' + esc(fmt.exact(it.at)) + '</span>';
  }

  /* Деньги одной зоной, как в «Моих направлениях»: сумма услуги крупно, под
     ней начисление короткой формой со звёздочкой. Ячейка и её сноска приходят
     одним вызовом общего блока — порознь сноску рано или поздно забывают
     позвать, и сумма выходит голой. Своей копии этого правила у экрана нет. */
  function money(it, bonus) {
    var cell = bonus.cell(it);
    return '<span class="bn-sum">' + (it.amount ? esc(fmt.money(it.amount)) : '') + '</span>' +
      '<span class="bn-sub">' + (cell ? 'начислено ' + cell : 'бонус считает клиника') + '</span>';
  }

  function payBadge(it) {
    return '<span class="badge badge--' + (it.paid ? 'ok' : 'quiet') + '">' +
      esc(it.status) + '</span>';
  }

  var COLS = [
    { title: 'Пациент', cls: 'bn-z1' },
    { title: 'Услуга и дата', cls: 'bn-z2' },
    { title: 'Сумма и начисление', cls: 'bn-z3', num: true },
    { title: 'Выплата', cls: 'bn-z4' }
  ];

  function history(b) {
    var bonus = w.Render.referralBonusColumn(b.items, { bar: true, barCls: 'bn-foot' });
    var n = b.items.length;
    return w.Render.zoneTable({
      cls: 'bn-table',
      cols: COLS,
      rows: b.items.map(function (it) {
        return {
          id: it.id, label: it.patientName,
          cells: [patient(it), service(it), money(it, bonus), payBadge(it)]
        };
      }),
      foot: {
        left: esc('Показаны все ' + n + ' ' +
                  fmt.plural(n, 'операция', 'операции', 'операций')),
        right: '<a class="act" href="vrach-zayavki.html">Открыть мои направления' +
          ic('arrow-right', 'ic--sm') + '</a>'
      }
    }) + bonus.footnote;
  }

  /* Подпись справа от линейки говорит про весь список сразу: сколько операций
     и сколько из них ещё ждут перевода. Второе число врач ищет первым. */
  function historyAside(b) {
    var n = b.items.length, pending = 0;
    b.items.forEach(function (it) { if (!it.paid) { pending++; } });
    return n + ' ' + fmt.plural(n, 'операция', 'операции', 'операций') +
      (pending ? ' · ' + pending + ' ' + fmt.plural(pending, 'ждёт', 'ждут', 'ждут') +
        ' выплаты' : '');
  }

  /* Пусто. Заказчик щёлкает «новый партнёр» и обязан увидеть объяснение,
     а не поломку (R14i): когда начисление появится и что для этого сделать.
     Значок в круге — вариант общего блока, тот же, что у пустой очереди
     модерации и пустого списка направлений. */
  function emptyBlock() {
    return '<div class="card bn-nothing">' + w.Render.emptyState({
      round: true,
      icon: 'card',
      title: 'Начислений пока нет',
      text: 'Начисление появится, когда направленный пациент придёт в клинику ' +
        'и получит услугу. До этого в истории пусто.',
      action: { href: 'vrach-napravlenie.html', text: 'Направить пациента' }
    }) + '</div>';
  }

  /* --- сборка экрана -----------------------------------------------------
     Три числа стоят сразу под заголовком экрана и своего заголовка не просят:
     заголовок у них — сам «Бонусы», а лишняя ступень отодвинула бы вниз то,
     ради чего экран открывают. Дальше — секция истории с линейкой, как в
     «Моих направлениях». */

  function render() {
    var b = w.DATA.bonuses();
    document.getElementById('page').innerHTML =
      '<h1 class="h1 page__title">Бонусы</h1>' +
      moneyCard(b) +
      section({
        title: 'История начислений',
        aside: b.items.length ? historyAside(b) : '',
        cls: 'bn-history',
        body: b.items.length ? history(b) : emptyBlock()
      });
  }

  function init() {
    /* Каркас увёл экран на главную чужой роли — рисовать уже нечего. */
    if (!w.Shell.mount({ active: 'vrach-bonusy', role: 'vrach' })) { return; }
    render();
  }

  if (document.readyState === 'loading') { document.addEventListener('DOMContentLoaded', init); } else { init(); }
})(window);
